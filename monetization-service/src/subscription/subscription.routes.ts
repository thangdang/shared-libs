import { Router, Request, Response } from 'express';
import { Subscription, SUBSCRIPTION_TIERS, SubscriptionTier, BillingCycle } from './subscription.model';
import mongoose from 'mongoose';

const router = Router();

/**
 * GET /subscriptions/plans
 * Get available subscription plans
 */
router.get('/plans', async (req: Request, res: Response) => {
  try {
    const { appId } = req.query;

    const plans = Object.entries(SUBSCRIPTION_TIERS).map(([tier, config]) => ({
      tier,
      name: config.name,
      price: config.price,
      features: config.features,
      description: config.description
    }));

    res.json({
      success: true,
      data: plans
    });
  } catch (error) {
    console.error('Error fetching plans:', error);
    res.status(500).json({
      success: false,
      error: 'Không thể tải danh sách gói'
    });
  }
});

/**
 * GET /subscriptions/current
 * Get current user's subscription
 */
router.get('/current', async (req: Request, res: Response) => {
  try {
    const userId = (req as any).userId; // From auth middleware
    const { appId } = req.query;

    if (!userId) {
      return res.status(401).json({
        success: false,
        error: 'Vui lòng đăng nhập'
      });
    }

    const subscription = await Subscription.findOne({
      userId: new mongoose.Types.ObjectId(userId),
      appId: appId as string
    });

    if (!subscription) {
      // Return free tier info
      return res.json({
        success: true,
        data: {
          tier: 'free',
          status: 'active',
          features: SUBSCRIPTION_TIERS.free.features
        }
      });
    }

    res.json({
      success: true,
      data: subscription
    });
  } catch (error) {
    console.error('Error fetching subscription:', error);
    res.status(500).json({
      success: false,
      error: 'Không thể tải thông tin gói'
    });
  }
});

/**
 * POST /subscriptions/subscribe
 * Create or upgrade subscription
 */
router.post('/subscribe', async (req: Request, res: Response) => {
  try {
    const userId = (req as any).userId;
    const { appId, tier, billingCycle = 'monthly' } = req.body;

    if (!userId) {
      return res.status(401).json({
        success: false,
        error: 'Vui lòng đăng nhập'
      });
    }

    if (!appId || !tier) {
      return res.status(400).json({
        success: false,
        error: 'Thiếu thông tin appId hoặc tier'
      });
    }

    const tierConfig = SUBSCRIPTION_TIERS[tier as SubscriptionTier];
    if (!tierConfig) {
      return res.status(400).json({
        success: false,
        error: 'Gói không hợp lệ'
      });
    }

    // Calculate price
    let price = 0;
    if (typeof tierConfig.price === 'object') {
      price = tierConfig.price[billingCycle as BillingCycle] || tierConfig.price.monthly;
    }

    // Calculate end date
    const startDate = new Date();
    const endDate = new Date();
    switch (billingCycle) {
      case 'yearly':
        endDate.setFullYear(endDate.getFullYear() + 1);
        break;
      case 'quarterly':
        endDate.setMonth(endDate.getMonth() + 3);
        break;
      default:
        endDate.setMonth(endDate.getMonth() + 1);
    }

    // Check existing subscription
    let subscription = await Subscription.findOne({
      userId: new mongoose.Types.ObjectId(userId),
      appId
    });

    if (subscription) {
      // Upgrade/change existing subscription
      subscription.tier = tier as SubscriptionTier;
      subscription.billingCycle = billingCycle as BillingCycle;
      subscription.price = price;
      subscription.finalPrice = price;
      subscription.status = 'pending'; // Pending payment
      subscription.endDate = endDate;
      subscription.features = {
        ...tierConfig.features,
        customFeatures: {}
      };
      await subscription.save();
    } else {
      // Create new subscription
      subscription = await Subscription.create({
        userId: new mongoose.Types.ObjectId(userId),
        email: (req as any).userEmail || '',
        appId,
        appName: appId,
        tier,
        status: 'pending',
        billingCycle,
        price,
        finalPrice: price,
        startDate,
        endDate,
        features: {
          ...tierConfig.features,
          customFeatures: {}
        },
        usage: {
          apiCalls: 0,
          storageUsed: 0
        }
      });
    }

    // Return payment URL (to be integrated with VNPay/MoMo)
    res.json({
      success: true,
      data: {
        subscriptionId: subscription._id,
        tier,
        price,
        billingCycle,
        endDate,
        paymentRequired: price > 0,
        // paymentUrl will be generated by payment gateway
      }
    });
  } catch (error) {
    console.error('Error creating subscription:', error);
    res.status(500).json({
      success: false,
      error: 'Không thể tạo gói đăng ký'
    });
  }
});

/**
 * POST /subscriptions/cancel
 * Cancel subscription
 */
router.post('/cancel', async (req: Request, res: Response) => {
  try {
    const userId = (req as any).userId;
    const { appId, reason } = req.body;

    if (!userId) {
      return res.status(401).json({
        success: false,
        error: 'Vui lòng đăng nhập'
      });
    }

    const subscription = await Subscription.findOne({
      userId: new mongoose.Types.ObjectId(userId),
      appId
    });

    if (!subscription) {
      return res.status(404).json({
        success: false,
        error: 'Không tìm thấy gói đăng ký'
      });
    }

    subscription.status = 'cancelled';
    subscription.cancelledAt = new Date();
    subscription.autoRenew = false;
    subscription.metadata = {
      ...subscription.metadata,
      cancelReason: reason
    };
    await subscription.save();

    res.json({
      success: true,
      message: 'Đã hủy gói đăng ký. Bạn vẫn có thể sử dụng đến hết ngày ' + 
               subscription.endDate.toLocaleDateString('vi-VN')
    });
  } catch (error) {
    console.error('Error cancelling subscription:', error);
    res.status(500).json({
      success: false,
      error: 'Không thể hủy gói đăng ký'
    });
  }
});

