/**
 * GET /subscriptions/usage
 * Get usage statistics for current subscription
 */
router.get('/usage', async (req: Request, res: Response) => {
  try {
    const userId = (req as any).userId;
    const { appId } = req.query;

    if (!userId) {
      return res.status(401).json({
        success: false,
        error: 'Vui lòng đăng nhập'
      });
    }

    const subscription = await Subscription.findOne({
      userId: new mongoose.Types.ObjectId(userId),
      appId
    });

    if (!subscription) {
      return res.json({
        success: true,
        data: {
          tier: 'free',
          usage: { apiCalls: 0, storageUsed: 0 },
          limits: SUBSCRIPTION_TIERS.free.features
        }
      });
    }

    res.json({
      success: true,
      data: {
        tier: subscription.tier,
        usage: subscription.usage,
        limits: subscription.features,
        percentUsed: {
          apiCalls: subscription.features.maxApiCalls && subscription.features.maxApiCalls > 0
            ? (subscription.usage.apiCalls / subscription.features.maxApiCalls) * 100
            : 0,
          storage: subscription.features.maxStorage && subscription.features.maxStorage > 0
            ? (subscription.usage.storageUsed / subscription.features.maxStorage) * 100
            : 0
        }
      }
    });
  } catch (error) {
    console.error('Error fetching usage:', error);
    res.status(500).json({
      success: false,
      error: 'Không thể tải thông tin sử dụng'
    });
  }
});

/**
 * POST /subscriptions/webhook/payment
 * Handle payment webhook (VNPay/MoMo callback)
 */
router.post('/webhook/payment', async (req: Request, res: Response) => {
  try {
    const { subscriptionId, transactionId, status, paymentMethod } = req.body;

    // Verify webhook signature (implementation depends on payment provider)
    // ...

    const subscription = await Subscription.findById(subscriptionId);
    if (!subscription) {
      return res.status(404).json({
        success: false,
        error: 'Subscription not found'
      });
    }

    if (status === 'success') {
      subscription.status = 'active';
      subscription.lastPaymentId = transactionId;
      subscription.lastPaymentDate = new Date();
      subscription.paymentMethod = paymentMethod;
      subscription.nextBillingDate = subscription.endDate;
    } else {
      subscription.status = 'pending';
      subscription.metadata = {
        ...subscription.metadata,
        lastPaymentError: status
      };
    }

    await subscription.save();

    res.json({
      success: true,
      message: 'Webhook processed'
    });
  } catch (error) {
    console.error('Error processing payment webhook:', error);
    res.status(500).json({
      success: false,
      error: 'Webhook processing failed'
    });
  }
});

